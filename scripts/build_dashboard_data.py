"""Package the analysis outputs into dashboard/data.js for the local web dashboard.

The data is written as a JavaScript file (not JSON) so the dashboard also works
when index.html is opened straight from disk, where browsers block fetch().

Usage:  python scripts/build_dashboard_data.py
Needs:  outputs/association_rules.csv (notebook) and outputs/sql_results/ (run_sql.py)
"""
import json
from datetime import date
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
SQL = OUT / "sql_results"
TARGET = ROOT / "dashboard" / "data.js"


def records(path, columns=None):
    df = pd.read_csv(path)
    if columns:
        df = df[columns]
    return json.loads(df.to_json(orient="records"))


def main():
    data = {
        "generated": date.today().isoformat(),
        "kpis": records(SQL / "overall_kpis.csv")[0],
        "rules": records(OUT / "association_rules.csv",
                         ["rank", "antecedents", "consequents", "rule_size", "support", "confidence", "lift", "baskets"]),
        "products": records(SQL / "product_performance.csv",
                            ["product_name", "category", "transactions", "support", "revenue"]),
        "monthly": records(SQL / "monthly_summary.csv"),
        "basketSizes": records(SQL / "basket_size_distribution.csv"),
        "weekdayHour": records(SQL / "weekday_hour_summary.csv"),
        "categories": records(SQL / "category_performance.csv"),
    }
    TARGET.write_text("// Generated by scripts/build_dashboard_data.py. Do not edit by hand.\n"
                      f"window.DASHBOARD_DATA = {json.dumps(data, separators=(',', ':'))};\n")
    print(f"wrote {TARGET.relative_to(ROOT)} ({TARGET.stat().st_size / 1024:.0f} KB, {len(data['rules'])} rules)")


if __name__ == "__main__":
    main()
